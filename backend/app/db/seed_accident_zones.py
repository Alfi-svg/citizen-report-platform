async def seed_accident_zones(db: AsyncSession) -> int:
    """
    Idempotently seeds documented Bangladesh accident-prone zones based on ARI BUET, BRTA, Highway Police.
    Returns the count of newly inserted zones.
    """
    inserted = 0
    now = datetime.now(timezone.utc)

    for item in DOCUMENTED_ACCIDENT_ZONES:
        stmt = select(AccidentZone).where(AccidentZone.zone_name == item["zone_name"])
        res = await db.execute(stmt)
        existing = res.scalars().first()

        if not existing:
            zone = AccidentZone(
                id=uuid.uuid4(),
                zone_name=item["zone_name"],
                zone_name_bn=item.get("zone_name_bn"),
                road_name=item["road_name"],
                district=item["district"],
                division=item["division"],
                latitude=item["latitude"],
                longitude=item["longitude"],
                radius_meters=item["radius_meters"],
                accident_count=item.get("accident_count"),
                observation_period=item.get("observation_period"),
                data_source=item["data_source"],
                source_url=item.get("source_url"),
                verification_status=item["verification_status"],
                risk_level=item["risk_level"],
                description=item.get("description"),
                description_bn=item.get("description_bn"),
                last_updated=now,
            )
            db.add(zone)
            inserted += 1

    if inserted > 0:
        await db.commit()

    return inserted
